# Write a program to calculate the number of notes in the given amount?

amount = int(input("Enter the amount : "))

five_hundred = amount // 500

two_hundered = amount // 200

hundred = amount // 100

fifty = amount // 50

twenty = amount // 20

tens = amount // 10

print("No of 500 notes : ", five_hundred)

print("No of 200 notes : ", two_hundered)

print("No of 100 notes : ", hundred)

print("No of 50 notes : ", fifty)

print("No of 20 notes : ", twenty)

print("No of 10 notes : ", tens)